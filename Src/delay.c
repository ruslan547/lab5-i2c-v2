/**
  ******************************************************************************
  * @file    delay.c
  * @brief   Программные задержки на холостом цикле.
  *
  * Задержки намеренно построены без использования периферийных блоков
  * (SysTick, TIMx): это гарантирует их работоспособность как на реальном
  * кристалле, так и в системах моделирования, где отдельные блоки могут
  * быть реализованы не полностью. Длительность цикла пересчитывается по
  * текущей частоте ядра SystemCoreClock, поэтому задержки сохраняются
  * и при работе от HSI 16 МГц, и при работе от PLL 84 МГц.
  *
  * Погрешность метода составляет единицы процентов, что для управления
  * знакосинтезирующим индикатором HD44780 несущественно: указанные в его
  * документации значения являются минимально допустимыми.
  ******************************************************************************
  */

#include "delay.h"
#include "clock.h"

/* Оценка числа тактов ядра на один проход холостого цикла */
#define LOOP_CYCLES     4UL

void delay_init(void)
{
    /* Инициализация не требуется: периферия не используется. */
}

void delay_us(uint32_t us)
{
    uint32_t f_mhz = SystemCoreClock / 1000000UL;
    volatile uint32_t count;

    if (f_mhz == 0UL)
        f_mhz = 16UL;

    count = (us * f_mhz) / LOOP_CYCLES;
    while (count--) {
        __NOP();
    }
}

void delay_ms(uint32_t ms)
{
    while (ms--)
        delay_us(1000UL);
}
